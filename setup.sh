#!/bin/bash

# ═══════════════════════════════════════════════════════════════════════════
# Dotfiles Setup Wizard
# Run this first to configure your dotfiles before installation
# ═══════════════════════════════════════════════════════════════════════════

set -e

DOTFILES_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_FILE="$DOTFILES_DIR/config.local"

echo ""
echo "╔═══════════════════════════════════════════════════════════════╗"
echo "║              🚀 Dotfiles Setup Wizard                         ║"
echo "╚═══════════════════════════════════════════════════════════════╝"
echo ""

# Check if config already exists
if [ -f "$CONFIG_FILE" ]; then
    echo "⚠️  config.local already exists."
    read -p "   Overwrite? (y/N): " overwrite
    if [[ ! "$overwrite" =~ ^[Yy]$ ]]; then
        echo "   Keeping existing config. Run ./install.sh to continue."
        exit 0
    fi
fi

echo "Let's configure your dotfiles..."
echo ""

# ===== User Info =====
echo "📝 Git Configuration"
echo "─────────────────────"
read -p "   Your name: " git_name
read -p "   Your email: " git_email
echo ""

# ===== Editor =====
echo "📝 Default Editor"
echo "─────────────────────"
echo "   Options: cursor, code, zed, vim, nvim"
read -p "   Editor [cursor]: " editor
editor=${editor:-cursor}
echo ""

# ===== Node.js =====
echo "📝 Node.js Version"
echo "─────────────────────"
read -p "   Version [24]: " node_version
node_version=${node_version:-24}
echo ""

# ===== Optional Tools =====
echo "📝 Optional Tools"
echo "─────────────────────"
read -p "   Install Ghostty (terminal)? (Y/n): " install_ghostty
install_ghostty=${install_ghostty:-Y}
[[ "$install_ghostty" =~ ^[Yy]$ ]] && install_ghostty="true" || install_ghostty="false"

read -p "   Install T3 Code (AI agent app)? (Y/n): " install_t3code
install_t3code=${install_t3code:-Y}
[[ "$install_t3code" =~ ^[Yy]$ ]] && install_t3code="true" || install_t3code="false"

read -p "   Install Zed (editor)? (Y/n): " install_zed
install_zed=${install_zed:-Y}
[[ "$install_zed" =~ ^[Yy]$ ]] && install_zed="true" || install_zed="false"

read -p "   Install OpenCode (AI assistant)? (y/N): " install_opencode
install_opencode=${install_opencode:-N}
[[ "$install_opencode" =~ ^[Yy]$ ]] && install_opencode="true" || install_opencode="false"

read -p "   Install DDEV (PHP development)? (Y/n): " install_ddev
install_ddev=${install_ddev:-Y}
[[ "$install_ddev" =~ ^[Yy]$ ]] && install_ddev="true" || install_ddev="false"

read -p "   Install OrbStack (Docker)? (Y/n): " install_orbstack
install_orbstack=${install_orbstack:-Y}
[[ "$install_orbstack" =~ ^[Yy]$ ]] && install_orbstack="true" || install_orbstack="false"
echo ""

# ===== macOS Settings =====
echo "📝 macOS Settings"
echo "─────────────────────"
read -p "   Show hidden files in Finder? (Y/n): " macos_hidden
macos_hidden=${macos_hidden:-Y}
[[ "$macos_hidden" =~ ^[Yy]$ ]] && macos_hidden="true" || macos_hidden="false"

read -p "   Auto-hide Dock? (Y/n): " macos_dock
macos_dock=${macos_dock:-Y}
[[ "$macos_dock" =~ ^[Yy]$ ]] && macos_dock="true" || macos_dock="false"

read -p "   Fast key repeat? (Y/n): " macos_keyrepeat
macos_keyrepeat=${macos_keyrepeat:-Y}
[[ "$macos_keyrepeat" =~ ^[Yy]$ ]] && macos_keyrepeat="true" || macos_keyrepeat="false"

read -p "   Tap to click on trackpad? (Y/n): " macos_tap
macos_tap=${macos_tap:-Y}
[[ "$macos_tap" =~ ^[Yy]$ ]] && macos_tap="true" || macos_tap="false"

read -p "   Screenshots folder [$HOME/Pictures/Screenshots]: " screenshots_dir
screenshots_dir=${screenshots_dir:-$HOME/Pictures/Screenshots}
echo ""

if [ -z "$git_name" ] || [ -z "$git_email" ]; then
    echo "❌ Git name and email are required. Run setup again."
    exit 1
fi
case "$editor" in
    cursor|code|zed|vim|nvim|nano) ;;
    *) echo "❌ Unsupported editor: $editor"; exit 1 ;;
esac

# ===== Write config =====
echo "💾 Saving configuration..."

umask 077
{
    echo "# Dotfiles Configuration — generated by setup.sh"
    printf 'GIT_USER_NAME=%q\n' "$git_name"
    printf 'GIT_USER_EMAIL=%q\n' "$git_email"
    printf 'DEFAULT_EDITOR=%q\n' "$editor"
    printf 'NODE_VERSION=%q\n' "$node_version"
    printf 'INSTALL_GHOSTTY=%q\n' "$install_ghostty"
    printf 'INSTALL_T3CODE=%q\n' "$install_t3code"
    printf 'INSTALL_ZED=%q\n' "$install_zed"
    printf 'INSTALL_OPENCODE=%q\n' "$install_opencode"
    printf 'INSTALL_DDEV=%q\n' "$install_ddev"
    printf 'INSTALL_ORBSTACK=%q\n' "$install_orbstack"
    printf 'MACOS_SHOW_HIDDEN_FILES=%q\n' "$macos_hidden"
    printf 'MACOS_DOCK_AUTOHIDE=%q\n' "$macos_dock"
    printf 'MACOS_FAST_KEY_REPEAT=%q\n' "$macos_keyrepeat"
    printf 'MACOS_TAP_TO_CLICK=%q\n' "$macos_tap"
    printf 'MACOS_SCREENSHOTS_LOCATION=%q\n' "$screenshots_dir"
    printf 'SSH_KEY_EMAIL=%q\n' "$git_email"
} > "$CONFIG_FILE"
chmod 600 "$CONFIG_FILE"

echo ""
echo "✅ Configuration saved to config.local"
echo ""
echo "Next steps:"
echo "  1. Review config.local if needed"
echo "  2. Run: ./install.sh"
echo ""
